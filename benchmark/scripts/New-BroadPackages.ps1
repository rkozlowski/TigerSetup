#Requires -Version 7.0
<#
    .SYNOPSIS
    Generates the broad benchmark's package definitions — one TigerSetup
    manifest, one Inno Setup script and one NSIS script per corpus
    application — from the campaign's corpus record and the common package
    contract (benchmark/packages/broad/contract.md).

    .DESCRIPTION
    The three definitions of an application differ only in what each
    technology needs to state the same small contract: install the
    canonical payload tree into the directory the command line names, in
    user scope, register the package with Add/Remove Programs through the
    technology's own mechanism, and remove all of it on uninstall. No
    shortcut, option, association, registry integration or custom action is
    declared anywhere, so a difference between two installers of one
    application is the technology's, not the script's.

    Every definition references its payload relative to itself (the corpus
    record's payloadRoot is relative to benchmark/), so a definition never
    carries a machine path, and every definition names the same
    identity — Benchmark.<App>, the application's three-part package
    version, one publisher string — so the three Add/Remove Programs entries
    of one application are comparable.

    The output is deterministic: the same corpus record produces the same
    files, and a definition that already matches is left untouched.

    .EXAMPLE
    pwsh -File benchmark\scripts\New-BroadPackages.ps1 -CorpusJson benchmark\results\0.10.0-broad\corpus.json
#>
[CmdletBinding()]
param(
    [string] $CorpusJson = (Join-Path $PSScriptRoot '..\results\0.10.0-broad\corpus.json'),
    [string] $PackagesRoot = (Join-Path $PSScriptRoot '..\packages\broad')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$benchmarkRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$PackagesRoot = [System.IO.Path]::GetFullPath($PackagesRoot)
$corpus = Get-Content -LiteralPath $CorpusJson -Raw | ConvertFrom-Json
$publisher = 'TigerSetup broad benchmark'

function Get-Prop { param([object] $Object, [string] $Name) if ($null -eq $Object -or $Object.PSObject.Properties.Match($Name).Count -eq 0) { return $null }; $Object.$Name }

function Write-IfChanged {
    param([string] $Path, [string] $Content)
    $null = New-Item -ItemType Directory -Path (Split-Path -Parent $Path) -Force
    if ((Test-Path -LiteralPath $Path -PathType Leaf) -and ((Get-Content -LiteralPath $Path -Raw) -eq $Content)) { return $false }
    [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
    $true
}

$written = 0
foreach ($app in @($corpus.apps)) {
    $name = [string] $app.app
    $dir = $name.ToLowerInvariant()
    $version = [string] $app.packageVersion
    # The definition sits four levels below benchmark/ (packages/broad/<app>/<technology>/).
    $payloadRelative = '../../../../' + [string] $app.payloadRoot
    $payloadBackslash = $payloadRelative.Replace('/', '\')
    $appRoot = Join-Path $PackagesRoot $dir
    # The corpus record names what no package installs (contract.md: the
    # reserved .tigersetup/ directory of a payload decomposed from a
    # TigerSetup installer); each technology states it its own way.
    $excludes = @(Get-Prop $app 'packageExcludes')
    $tomlExclude = $(if ($excludes.Count -gt 0) { "`nexclude = [" + (($excludes | ForEach-Object { '"' + $_ + '"' }) -join ', ') + ']' } else { '' })
    # Inno Setup: a pattern starting with a backslash is matched against the
    # beginning of the path relative to the source directory.
    $issExclude = $(if ($excludes.Count -gt 0) { '; Excludes: "' + (($excludes | ForEach-Object { '\' + ($_ -replace '/\*\*$', '\*').Replace('/', '\') }) -join ',') + '"' } else { '' })
    $nsiExclude = $(if ($excludes.Count -gt 0) { (($excludes | ForEach-Object { '/x "' + ($_ -replace '/\*\*$', '') + '" ' }) -join '') } else { '' })

    $toml = @"
# $name $($app.version) broad-benchmark package (TigerSetup). The common
# contract is ../../contract.md; this file is generated by
# scripts/New-BroadPackages.ps1 from the campaign's corpus record. The
# payload is the canonical $name payload, referenced relative to this
# manifest.

[package]
id = "Benchmark.$name"
name = "$name"
version = "$version"
publisher = "$publisher"

[install]
scopes = ["user"]

[[files]]
source = "$payloadRelative/**"$tomlExclude
"@

    $iss = @"
; $name $($app.version) broad-benchmark package (Inno Setup 7). The common
; contract is ..\..\contract.md; this file is generated by
; scripts\New-BroadPackages.ps1 from the campaign's corpus record. The
; payload is the canonical $name payload, referenced relative to this script.
;
; Compression: LZMA2/max, solid -- the benchmark's production-quality
; setting for all three technologies (see benchmark\README.md).

#define MyAppName "$name"
#define MyAppVersion "$version"
#define MyAppPublisher "$publisher"
#define PayloadDir "$payloadBackslash"

[Setup]
AppId=Benchmark.$name
AppName={#MyAppName}
AppVersion={#MyAppVersion}
AppPublisher={#MyAppPublisher}
DefaultDirName={autopf}\{#MyAppName}
DisableProgramGroupPage=yes
PrivilegesRequired=lowest
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
Compression=lzma2/max
SolidCompression=yes
OutputDir=..\..\..\..\artifacts\broad\$dir
OutputBaseFilename=$name-InnoSetup

[Files]
Source: "{#PayloadDir}\*"; DestDir: "{app}"; Flags: recursesubdirs ignoreversion$issExclude
"@

    $nsi = @"
; $name $($app.version) broad-benchmark package (NSIS 3.12). The common
; contract is ..\..\contract.md; this file is generated by
; scripts\New-BroadPackages.ps1 from the campaign's corpus record. The
; payload is the canonical $name payload, referenced relative to this script.
;
; Compression: LZMA, solid -- the benchmark's production-quality setting for
; all three technologies (see benchmark\README.md).

Unicode true

!define APP_NAME "$name"
!define APP_VERSION "$version"
!define APP_PUBLISHER "$publisher"
!define PAYLOAD_DIR "$payloadBackslash"
!define UNINSTALL_KEY "Software\Microsoft\Windows\CurrentVersion\Uninstall\Benchmark.$name"

!include "FileFunc.nsh"

Name "`${APP_NAME}"
; The output path is the definition's own unless the build passes
; /DOUTFILE=<path> (Build-Installers.ps1 does, per campaign).
!ifndef OUTFILE
  !define OUTFILE "..\..\..\..\artifacts\broad\$dir\$name-NSIS.exe"
!endif
OutFile "`${OUTFILE}"
InstallDir "`$LOCALAPPDATA\Programs\`${APP_NAME}"
RequestExecutionLevel user
SetCompressor /SOLID lzma

VIProductVersion "`${APP_VERSION}.0"
VIAddVersionKey "ProductName" "`${APP_NAME}"
VIAddVersionKey "ProductVersion" "`${APP_VERSION}"
VIAddVersionKey "CompanyName" "`${APP_PUBLISHER}"
VIAddVersionKey "FileVersion" "`${APP_VERSION}.0"

Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section "Install"
  SetShellVarContext current
  SetOutPath "`$INSTDIR"
  File /r $nsiExclude"`${PAYLOAD_DIR}\*.*"
  WriteUninstaller "`$INSTDIR\Uninstall.exe"

  WriteRegStr HKCU "`${UNINSTALL_KEY}" "DisplayName" "`${APP_NAME}"
  WriteRegStr HKCU "`${UNINSTALL_KEY}" "DisplayVersion" "`${APP_VERSION}"
  WriteRegStr HKCU "`${UNINSTALL_KEY}" "Publisher" "`${APP_PUBLISHER}"
  WriteRegStr HKCU "`${UNINSTALL_KEY}" "InstallLocation" "`$INSTDIR"
  WriteRegStr HKCU "`${UNINSTALL_KEY}" "UninstallString" '"`$INSTDIR\Uninstall.exe"'
  WriteRegStr HKCU "`${UNINSTALL_KEY}" "QuietUninstallString" '"`$INSTDIR\Uninstall.exe" /S'
  `${GetSize} "`$INSTDIR" "/S=0K" `$0 `$1 `$2
  WriteRegDWORD HKCU "`${UNINSTALL_KEY}" "EstimatedSize" "`$0"
  WriteRegDWORD HKCU "`${UNINSTALL_KEY}" "NoModify" 1
  WriteRegDWORD HKCU "`${UNINSTALL_KEY}" "NoRepair" 1
SectionEnd

Section "Uninstall"
  SetShellVarContext current
  RMDir /r "`$INSTDIR"
  DeleteRegKey HKCU "`${UNINSTALL_KEY}"
SectionEnd
"@

    foreach ($pair in @(
            @((Join-Path $appRoot 'tigersetup\TigerSetup.toml'), $toml),
            @((Join-Path $appRoot "innosetup\$name.iss"), $iss),
            @((Join-Path $appRoot "nsis\$name.nsi"), $nsi))) {
        if (Write-IfChanged -Path $pair[0] -Content $pair[1]) { $written++ }
    }
}
Write-Host "Package definitions for $(@($corpus.apps).Count) application(s) under $PackagesRoot ($written file(s) written)"
