#Requires -Version 7.0
<#
    .SYNOPSIS
    Writes a cspike plan: the Cartesian product of the given apps,
    partitions, layouts, settings and block sizes, with the ordered file
    lists it needs generated by `cspike layout` from the committed
    inventories.

    .DESCRIPTION
    A setting is named like the results label it: `store`, `deflate-9`,
    `zstd-19`, `zstd-19-w27` (window log 27 with long-distance matching),
    `lzma2-9`, `lzma2-9e` (extreme preset), `lzma2-9-bcj` (x86 BCJ filter
    ahead of LZMA2). Apps default to every
    inventoried payload, largest first so that the long jobs start early.

    .EXAMPLE
    pwsh -File scripts\New-Plan.ps1 -Name stage1 -Settings store,deflate-9,zstd-3,zstd-12,zstd-19,zstd-19-w27,zstd-22-w27,lzma2-3,lzma2-6,lzma2-9,lzma2-9e -Parallelism 2
    tool\target\x86_64-pc-windows-msvc\release\cspike.exe run --plan work\plans\stage1.json --results results\stage1.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $Name,
    [string[]] $Apps,
    [string[]] $Partitions = @('current'),
    [string[]] $Layouts = @('path'),
    [Parameter(Mandatory)] [string[]] $Settings,
    # Uncompressed block targets in bytes; 0 means one solid stream.
    [string[]] $BlockBytes = @("0"),
    [int] $CompressReps = 1,
    [int] $DecompressReps = 3,
    [switch] $PerFile,
    [int] $Parallelism = 2
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# `pwsh -File` passes "a,b" as one string: split every list parameter.
function Split-List([string[]] $values) { @($values | ForEach-Object { $_ -split ',' } | Where-Object { $_ }) }
$Apps = Split-List $Apps; $Partitions = Split-List $Partitions; $Layouts = Split-List $Layouts; $Settings = Split-List $Settings
# A typed parameter variable keeps its [string[]] constraint, so the numbers get a name of their own.
$blockSizes = @($BlockBytes | ForEach-Object { "$_" -split ',' } | ForEach-Object { [long]$_ })
$root = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$tool = Join-Path $root 'tool\target\x86_64-pc-windows-msvc\release\cspike.exe'
$inventoryDir = Join-Path $root 'results\inventory'
$listDir = Join-Path $root 'work\lists'
$planDir = Join-Path $root 'work\plans'
$null = New-Item -ItemType Directory -Path $listDir, $planDir, (Join-Path $root 'work\run') -Force

function ConvertTo-Setting([string] $label) {
    switch -Regex ($label) {
        '^store$' { return [ordered]@{ codec = 'store'; level = 0; extreme = $false } }
        '^deflate-(\d+)$' { return [ordered]@{ codec = 'deflate'; level = [int]$Matches[1]; extreme = $false } }
        '^zstd-(\d+)(?:-w(\d+))?$' {
            $s = [ordered]@{ codec = 'zstd'; level = [int]$Matches[1]; extreme = $false }
            if ($Matches.Count -gt 2 -and $Matches[2]) { $s.window_log = [int]$Matches[2] }
            return $s
        }
        '^lzma2-(\d+)(e?)(?:-w(\d+))?(-bcj)?$' {
            $s = [ordered]@{ codec = 'lzma2'; level = [int]$Matches[1]; extreme = ($Matches[2] -eq 'e'); bcj = ($label -like '*-bcj') }
            if ($Matches.Count -gt 3 -and $Matches[3]) { $s.window_log = [int]$Matches[3] }
            return $s
        }
        default { throw "Unknown setting label '$label'" }
    }
}

$inventories = @(Get-ChildItem -LiteralPath $inventoryDir -Filter '*.json' | ForEach-Object {
    $d = Get-Content -LiteralPath $_.FullName -Raw | ConvertFrom-Json
    [PSCustomObject]@{ app = $d.app; bytes = [long]$d.total_bytes; path = $_.FullName }
} | Sort-Object -Property bytes -Descending)
if ($Apps) { $inventories = @($inventories | Where-Object { $_.app -in $Apps }) }

$jobs = @()
foreach ($inv in $inventories) {
    foreach ($partition in $Partitions) {
        foreach ($layout in $Layouts) {
            $list = Join-Path $listDir "$($inv.app)-$partition-$layout.json"
            if (-not (Test-Path -LiteralPath $list)) {
                & $tool layout --inventory $inv.path --partition $partition --layout $layout --out $list
                if ($LASTEXITCODE -ne 0) { throw "cspike layout failed for $($inv.app) $partition $layout" }
            }
            foreach ($label in $Settings) {
                foreach ($block in $blockSizes) {
                    $id = "$($inv.app)/$partition/$layout/$label"
                    if ($PerFile) { $id += '/per-file' }
                    if ($block -gt 0) { $id += "/block-$([int]($block / 1MB))MiB" }
                    $job = [ordered]@{
                        id              = $id
                        app             = $inv.app
                        partition       = $partition
                        layout          = $layout
                        list            = $list
                        setting         = (ConvertTo-Setting $label)
                        compress_reps   = $CompressReps
                        decompress_reps = $DecompressReps
                        per_file        = [bool]$PerFile
                    }
                    if ($block -gt 0) { $job.block_bytes = $block }
                    $jobs += $job
                }
            }
        }
    }
}

$plan = [ordered]@{
    parallelism = $Parallelism
    work_dir    = (Join-Path $root 'work\run')
    jobs        = $jobs
}
$out = Join-Path $planDir "$Name.json"
$plan | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $out -Encoding utf8
Write-Host "Wrote $out ($($jobs.Count) jobs)"
